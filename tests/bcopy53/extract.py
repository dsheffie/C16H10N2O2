#!/usr/bin/env python3
# extract.py <unix53.elf> <name> <lo> <hi> <out.S>: copy an IRIX 5.3 kernel routine
# (vaddr [lo, hi)) verbatim into an assembly file as .word directives, so the tests run
# SGI's own code without it living in this repo.  bcopy: 0x88015700 0x88015b48,
# blkclr: 0x88015110 0x880151bc (unix53 = the IRIX 5.3 IP22 kernel, ECOFF -> ELF).
import struct, subprocess, sys

elf, name, lo, hi, out = sys.argv[1], sys.argv[2], int(sys.argv[3], 0), int(sys.argv[4], 0), sys.argv[5]
va = off = None
for l in subprocess.run(["mips-linux-gnu-readelf", "-S", elf], capture_output=True, text=True).stdout.splitlines():
    if " .text " in l:
        p = l.split()
        i = p.index(".text")
        va, off = int(p[i + 2], 16), int(p[i + 3], 16)
d = open(elf, "rb").read()[off + (lo - va):off + (hi - va)]
words = struct.unpack(">%dI" % (len(d) // 4), d)
with open(out, "w") as f:
    f.write(f"/* {name}: IRIX 5.3 kernel 0x{lo:08x}-0x{hi:08x}, generated by extract.py */\n")
    f.write(f"    .set noreorder\n    .text\n    .globl {name}\n{name}:\n")
    for w in words:
        f.write(f"    .word 0x{w:08x}\n")
